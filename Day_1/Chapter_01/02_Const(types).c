/*=====================================================
              TYPES OF CONSTANTS IN C
=======================================================

Constants are fixed values that do not change during
the execution of a program.

There are mainly three types of constants in C:

-------------------------------------------------------
1. Integer Constants
-------------------------------------------------------

An integer constant is a whole number without a
decimal point.

Examples:
1
6
7
9
100
-25
0

Program:

int age = 18;
int marks = 95;

-------------------------------------------------------
2. Real (Floating-Point) Constants
-------------------------------------------------------

A real constant is a number that contains a
decimal point.

Examples:
322.1
2.5
7.0
3.14
-10.75

Program:

float pi = 3.14;
float temperature = 36.5;

-------------------------------------------------------
3. Character Constants
-------------------------------------------------------

A character constant is a single character enclosed
within single quotes (' ').

Examples:
'A'
'a'
'9'
'$'
'@'

Program:

char grade = 'A';
char symbol = '$';
char digit = '5';

Note:
✔ A character constant can contain only ONE character.

Correct:
'A'
'7'
'@'

Incorrect:
"AB"     // String (double quotes)
'AB'     // More than one character

-------------------------------------------------------
Difference Between Character and String
-------------------------------------------------------

Character:
'A'
'$'
'5'

String:
"Hello"
"Raj"
"C Programming"

Character → Single quotes (' ')
String → Double quotes (" ")

-------------------------------------------------------
Quick Revision
-------------------------------------------------------

1. Integer Constant
   ✔ Whole numbers
   Example: 10, -5, 100

2. Real Constant
   ✔ Decimal numbers
   Example: 3.14, 25.5, 0.75

3. Character Constant
   ✔ Single character inside single quotes
   Example: 'A', '$', '7'

=====================================================*/
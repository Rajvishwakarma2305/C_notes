/*=====================================================
                VARIABLES IN C (Beginner Notes)
=======================================================

📌 What is a Variable?
A variable is a container that stores data.

Example:
int age = 18;

Here,
int  -> Data type
age  -> Variable name
18   -> Value

-------------------------------------------------------
Rules for Variable Names
-------------------------------------------------------
✔ Can use letters (a-z, A-Z)
✔ Can use numbers (0-9)
✔ Can use underscore (_)

✔ Must start with:
   - Letter
   - Underscore (_)

❌ Cannot start with a number
❌ No spaces allowed
❌ No special characters (@ # $ %)
❌ Cannot use keywords (int, if, while...)

Good Names:
age
studentName
total_marks

Bad Names:
1age
my name
int

-------------------------------------------------------
Declaring Variables
-------------------------------------------------------

int age;
float price;
char grade;

-------------------------------------------------------
Initializing Variables
-------------------------------------------------------

int age = 18;
float price = 99.99;
char grade = 'A';

-------------------------------------------------------
Changing Value
-------------------------------------------------------

age = 20;

-------------------------------------------------------
Common Data Types
-------------------------------------------------------

int     -> Whole numbers
float   -> Decimal numbers
char    -> Single character

-------------------------------------------------------
Printing Variables
-------------------------------------------------------

printf("%d", age);      // int
printf("%f", price);    // float
printf("%c", grade);    // char

-------------------------------------------------------
Taking Input
-------------------------------------------------------

scanf("%d", &age);
scanf("%f", &price);
scanf("%c", &grade);

-------------------------------------------------------
Remember
-------------------------------------------------------

Variable = Name + Data Type + Value

Example:

int marks = 95;

Data Type     -> int
Variable Name -> marks
Value         -> 95

=====================================================*/
/*
Question:
3.0 + 1 will be:

a. Integer
b. Floating point number
c. Character

Answer:
b. Floating point number

Explanation:
- 3.0 is a floating-point number (double).
- 1 is an integer.
- C converts the integer (1) to 1.0 before addition.
- Therefore:
  3.0 + 1
= 3.0 + 1.0
= 4.0

Final Result:
4.0 (Floating Point Number)
*/